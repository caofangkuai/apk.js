import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const JSZip = require('jszip');
import { loadApkFiles, EmulatorEngine } from './src/framework/engine.js';
const eng=new EmulatorEngine({onLog:()=>{},width:360,height:720});
const apk=await loadApkFiles(await JSZip.loadAsync(fs.readFileSync('/tmp/devinfo.apk')));
await eng.start(apk);
const vm=eng.vm;
const dex=vm.dexFiles[0];
const m=dex.methods[0x4f6e];
console.log('ref', m.classDesc, m.name, m.proto?.descriptor ?? m.proto);
const rc=vm.registry.resolve(m.classDesc);
const real=[...(rc.dexClass?.directMethods||[]),...(rc.dexClass?.virtualMethods||[])].find(x=>x.name==='b'&&x.proto?.descriptor==='(Landroidx/appcompat/widget/Toolbar;)V');
console.log('real?', !!real, real?.classDesc, 'code?', !!real?.code);
